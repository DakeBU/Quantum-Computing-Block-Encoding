"""Isolated Lean certification for QuantumComputingBench formal items.

Design contract (see ``AGENT_GOAL.md`` lines 46-53 and 15):

* The *expected* theorem statement and its imports are **frozen** on the item
  (``item["formal_context"] = {"imports", "target"}``) and are trusted,
  hash-bound inputs produced by ``qcb_core.prepare`` / ``validate``.  The
  candidate supplies **only** a proof term, never the statement, imports,
  axiom policy, resource limits or any command.
* The candidate proof is restricted to a tiny, independently checked
  proof-term grammar (``by exact Fully.Qualified.lemma args`` or a bare
  application).  Arbitrary Lean -- ``#eval``, ``import``, ``set_option``,
  ``run_cmd``, new declarations, comments, strings, ``sorry`` -- is rejected
  *before* anything is handed to Lean, so a candidate cannot forge the trust
  marker, mutate the harness, read credentials or escape the sandbox.
* The harness itself is generated by this (trusted) module.  It elaborates
  ``theorem <frozen name> : <frozen target> := <checked candidate proof>`` and
  then calls ``Lean.collectAxioms`` to obtain the *transitive* axiom closure of
  that exact declaration, emitting a nonce-tagged report line.  Elaboration is
  the independent replay; ``collectAxioms`` is the trusted axiom check.
* A certificate requires: the harness binary exits cleanly, the nonce-tagged
  trust marker is present (an exit code, an empty goal list or a substring scan
  are *not* certificates), ``sorryAx`` is absent and the transitive axiom set is
  a subset of the fixed foundational policy.  The approved axiom set is
  **immutable** -- items cannot widen it.
* Replay runs inside a locked-down container: ``--network none``, an immutable
  image pinned by ``@sha256:``, an allowlisted sanitized subset of the project
  mounted read-only under ``/library`` (never ``.git``, the benchmark tree, or
  any ``private``/``gold`` material), a fresh bounded ``tmpfs`` scratch
  ``/work``, no credentials, non-root, and fixed memory / cpu / pids / wall /
  fuel caps that items cannot override.  Images are **never pulled** and Lean is
  **never installed**.

Certification is **disabled** unless an operator has explicitly provisioned and
vetted a pinned verifier image (``configs/offline.json`` ``lean.status`` must be
``"ENABLED"`` with a non-null ``container_image`` AND the trusted code
integration gate must be enabled only after real pinned-image integration tests).  The shipped configuration is ``ENV_BLOCKED``: the harness is
generated but **not executed**, and ``verify`` returns ``status="blocked"`` with
reason ``"env_blocked"``.  It never fabricates a certificate.  A timeout / OOM /
kill is reported as ``blocked`` (an environmental fact), and a type error or
missing lemma is reported as ``rejected`` with reason ``unproven`` -- never as a
mathematical refutation of the statement.

The execution path is fully implemented so a vetted isolated verifier can be
enabled later, and the pure helpers (grammar, harness assembly, axiom policy,
marker parsing, report evaluation, mount allowlist) are exercised by
``tests/test_lean.py`` without ever running Lean.
"""
from __future__ import annotations

import hashlib
import json
import os
import re
import secrets
import shutil
import subprocess
import tempfile
from pathlib import Path

RECEIPT_VERSION = "qcb.lean_receipt.v1"
# A real pinned-image integration replay has NOT run in this environment.
# This cannot be bypassed by an environment variable or candidate item.
HARNESS_INTEGRATION_TESTED = False

# Immutable, exact foundational axiom policy.  These are the classical axioms
# Mathlib/Lean legitimately rest on.  Items CANNOT extend this set; anything
# else -- above all ``sorryAx`` -- makes the proof not certifiable.
APPROVED_AXIOMS = frozenset({"Classical.choice", "Quot.sound", "propext"})

# Character whitelist for a candidate proof term: letters, digits, underscore,
# prime, dot (for qualified names), parentheses and whitespace.  Everything else
# -- quotes, ``#``, ``:``, ``=``, ``;``, ``-``, ``/``, operators, brackets,
# braces, anglequotes, ``$``, backtick, ``@`` -- is rejected, which rules out
# comments (``--`` ``/-``), ``:=``, ``=>``, ``<;>``, strings and ``#``-commands
# before the token grammar even runs.
_ALLOWED_CHARS = re.compile(r"[A-Za-z0-9_'(). \t\r\n]*\Z")

# A fully-qualified identifier: dotted components, Lean name chars.  Numeric
# literals and parentheses complete the restricted application grammar.
_IDENT = r"[A-Za-z_][A-Za-z0-9_']*(?:\.[A-Za-z_][A-Za-z0-9_']*)*"
_TOKEN = re.compile(rf"\s+|\(|\)|{_IDENT}|[0-9]+")
_ATOM_IDENT = re.compile(rf"{_IDENT}\Z")
_NUMBER = re.compile(r"[0-9]+\Z")

# Reserved keywords that must never appear as a *whole* token.  A qualified name
# whose component merely spells a keyword (e.g. ``Foo.by_cases``) tokenises as a
# single dotted identifier and is unaffected; only a bare keyword token -- which
# could start a second command/binder/tactic -- is rejected.
_RESERVED = frozenset({
    "by", "exact", "theorem", "lemma", "example", "def", "instance", "axiom",
    "opaque", "unsafe", "partial", "import", "open", "namespace", "section",
    "end", "set_option", "attribute", "macro", "macro_rules", "syntax", "elab",
    "elab_rules", "run_cmd", "run_elab", "initialize", "extern", "deriving",
    "sorry", "admit", "fun", "let", "match", "do", "show", "from", "calc",
    "have", "suffices", "where", "mutual", "inductive", "structure", "class",
    "abbrev", "notation", "infixl", "infixr", "prefix", "postfix", "in",
})

# Trusted-harness marker emitted by generated Lean.
_MARKER = "QCB_AXIOM_REPORT"

# Statement-level characters that must never appear in a *frozen* target.  The
# target is trusted/hash-bound, but we still refuse one that smuggles a proof
# slot (``:=``), a command (``#``), a comment or a string, so a malformed or
# adversarial item cannot widen the trust boundary.
_TARGET_FORBIDDEN = re.compile(r":=|#|--|/-|-/|\"|\bsorry\b|\badmit\b|\baxiom\b")

# Module name components: plain dotted identifiers only.
_MODULE = re.compile(rf"{_IDENT}\Z")

# Pinned-digest image reference, e.g. ``registry/lean@sha256:<64 hex>``.
_PINNED_IMAGE = re.compile(r"^[\w./:-]+@sha256:[0-9a-f]{64}$")

# Fixed, non-overridable fuel and resource caps.  Items may NOT change these.
FUEL_HEARTBEATS = 400_000
LIMITS = {
    "memory": "4g",
    "cpus": "2",
    "pids": 256,
    "wall_seconds": 300,
    "work_size": "512m",
    "user": "65534:65534",  # nobody:nogroup
    "stdout_cap": 1_000_000,
    "stderr_cap": 8_000,
}

# Allowlisted, non-sensitive library inputs mounted read-only into the sandbox.
# Everything NOT listed -- ``.git``, ``benchmarks`` (private gold lives there),
# any ``private``/``gold``/credential material -- is never exposed.
LIBRARY_ALLOWLIST = (
    "lakefile.lean",
    "lake-manifest.json",
    "lean-toolchain",
    "QuantumBlockEncoding.lean",
    "QuantumBlockEncoding",
    ".lake",
)
# Defensive deny-set: even if a future edit adds one of these to the allowlist,
# a mount that resolves to any of them is refused.
_MOUNT_DENY = ("..", ".git", "benchmarks", "private", "gold", "secrets", ".env")


class ProofGrammarError(ValueError):
    """Raised when a candidate proof leaves the restricted proof-term grammar."""


def validate_proof_grammar(proof: str) -> str:
    """Return a canonical, safe proof term or raise :class:`ProofGrammarError`.

    Accepts ``by exact <application>`` or a bare ``<application>`` where an
    application is a whitespace-separated sequence of fully-qualified
    identifiers, natural-number literals and parenthesised sub-applications.
    Everything else -- extra tactics, commands, operators, strings, comments,
    ``sorry`` -- is rejected.  Nothing is handed to Lean until this passes.
    """
    if not isinstance(proof, str):
        raise ProofGrammarError("proof must be text")
    text = proof.strip()
    if not text:
        raise ProofGrammarError("empty proof")
    if len(text) > 4000:
        raise ProofGrammarError("proof exceeds length bound")
    if not _ALLOWED_CHARS.match(text):
        bad = next(c for c in text if not _ALLOWED_CHARS.match(c))
        raise ProofGrammarError(f"illegal character {bad!r} in proof")

    body = text
    prefix = ""
    # Optional, fixed ``by exact`` lead-in; the only tactic admitted is exact.
    m = re.match(r"by[ \t\r\n]+exact[ \t\r\n]+", body)
    if m:
        prefix = "by exact "
        body = body[m.end():]

    tokens, depth, saw_atom = [], 0, False
    pos = 0
    for match in _TOKEN.finditer(body):
        if match.start() != pos:
            raise ProofGrammarError("unexpected character in proof")
        pos = match.end()
        tok = match.group(0)
        if tok.isspace():
            continue
        if tok == "(":
            depth += 1
        elif tok == ")":
            depth -= 1
            if depth < 0:
                raise ProofGrammarError("unbalanced parentheses")
        elif _ATOM_IDENT.match(tok):
            if tok in _RESERVED:
                raise ProofGrammarError(f"reserved keyword {tok!r} not allowed")
            saw_atom = True
        elif _NUMBER.match(tok):
            saw_atom = True
        else:  # pragma: no cover - regex alternation is exhaustive
            raise ProofGrammarError(f"illegal token {tok!r}")
        tokens.append(tok)
    if pos != len(body):
        raise ProofGrammarError("unexpected trailing characters")
    if depth != 0:
        raise ProofGrammarError("unbalanced parentheses")
    if not saw_atom:
        raise ProofGrammarError("proof has no lemma application")
    return prefix + " ".join(tokens)


def _trusted_target(target: str) -> str:
    """Validate the shape of the *frozen* theorem statement."""
    if not isinstance(target, str) or not target.strip():
        raise ValueError("frozen target missing")
    if "\n" in target:
        raise ValueError("frozen target must be a single statement")
    if _TARGET_FORBIDDEN.search(target):
        raise ValueError("frozen target contains a non-statement construct")
    return target.strip()


def _frozen_formal(item: dict) -> tuple[list[str], str]:
    """Extract frozen imports and target, validating their shape."""
    context = item.get("formal_context") or {}
    imports = context.get("imports")
    target = context.get("target")
    if not isinstance(imports, list) or not imports:
        raise ValueError("no frozen imports")
    clean: list[str] = []
    for name in imports:
        if not isinstance(name, str) or not _MODULE.match(name.strip()):
            raise ValueError(f"illegal import module {name!r}")
        clean.append(name.strip())
    return clean, _trusted_target(target)


def axiom_policy(item: dict | None = None) -> frozenset:
    """Return the immutable approved axiom set.

    The policy is fixed and foundational; items cannot extend or shrink it, so a
    crafted item can never get an extra axiom (or ``sorryAx``) approved.  The
    ``item`` argument is accepted for call-site symmetry and ignored.
    """
    return APPROVED_AXIOMS


def classify_axioms(reported, sorry_seen: bool, policy=APPROVED_AXIOMS):
    """Return ``(certified, offending_axioms)`` for a transitive axiom report."""
    policy = set(policy)
    offending = sorted(a for a in reported if a == "sorryAx" or a not in policy)
    certified = not sorry_seen and not offending
    return certified, offending


def _theorem_name(item: dict, nonce: str) -> str:
    tag = hashlib.sha256(f"{item.get('id','')}:{nonce}".encode()).hexdigest()[:16]
    return f"qcbCandidate_{tag}"


def build_harness(item: dict, proof: str, nonce: str) -> tuple[str, str]:
    """Assemble the trusted Lean harness. Returns ``(source, theorem_name)``.

    The frozen statement is placed verbatim; only the grammar-checked proof term
    fills the ``:=`` slot.  Fuel is the fixed, non-overridable cap.  After
    elaboration the harness calls ``Lean.collectAxioms`` on *that* declaration
    and prints a nonce-tagged marker.  The candidate cannot reach the marker
    code: its grammar forbids commands, strings and newlines, so it stays inside
    the proof term.
    """
    imports, target = _frozen_formal(item)
    safe_proof = validate_proof_grammar(proof)
    name = _theorem_name(item, nonce)
    import_lines = "\n".join(f"import {m}" for m in imports)
    # ``import Lean`` gives the harness ``collectAxioms``/elaborator APIs even if
    # the frozen imports do not transitively provide them.
    source = f"""import Lean
{import_lines}

set_option maxHeartbeats {FUEL_HEARTBEATS} in
theorem {name} : {target} := {safe_proof}

open Lean Elab Command in
elab "qcbEmitReport" : command => do
  let axioms ← liftCoreM (Lean.collectAxioms `{name})
  let names := axioms.toList.map Lean.Name.toString
  let sorrySeen := names.any (fun n => n == "sorryAx")
  let flag := if sorrySeen then "true" else "false"
  let joined := String.intercalate "," names
  logInfo s!"{_MARKER}|{nonce}|{{flag}}|{{joined}}"

qcbEmitReport
"""
    return source, name


def parse_harness_output(stdout: str, nonce: str) -> dict:
    """Parse the trusted marker. Raises if absent, duplicated or nonce-mismatched.

    An exit code or stray output is never accepted as a certificate; only the
    unique nonce-tagged line counts, and the ``sorry`` flag is parsed strictly.
    """
    found = []
    for raw in stdout.splitlines():
        line = raw.strip()
        if _MARKER not in line:
            continue
        payload = line[line.index(_MARKER):]
        parts = payload.split("|")
        if len(parts) != 4 or parts[0] != _MARKER:
            raise ValueError("malformed trust marker")
        if not secrets.compare_digest(parts[1], nonce):
            raise ValueError("trust marker nonce mismatch")
        flag = parts[2].strip()
        if flag not in ("true", "false"):
            raise ValueError("malformed sorry flag")
        names = [n for n in parts[3].split(",") if n]
        found.append({"sorry_seen": flag == "true", "axioms": names})
    if len(found) != 1:
        raise ValueError("trust marker absent or duplicated")
    return found[0]


def evaluate_report(exit_code: int, stdout: str, stderr: str, nonce: str,
                    policy=APPROVED_AXIOMS) -> dict:
    """Decide the outcome of one completed replay. Pure; no I/O.

    Returns ``{"status", "reason", ...}`` where ``status`` is one of
    ``certified`` / ``rejected`` / ``blocked``.  ``certified`` requires a clean
    exit, the unique nonce marker, no ``sorryAx`` and a policy-subset axiom set.
    """
    # 124 == `timeout` kill; 137 == 128+SIGKILL (OOM / pids); 125 run fail; 143 TERM.
    if exit_code in (124, 125, 137, 143):
        return {"status": "blocked", "reason": "resource_kill",
                "detail": "replay killed by timeout/OOM/pids cap"}
    if exit_code != 0:
        # Lean could not elaborate the proof: type error, missing lemma, extra
        # command.  This is an unproven candidate, NOT a refutation of the goal.
        return {"status": "rejected", "reason": "unproven"}
    try:
        report = parse_harness_output(stdout, nonce)
    except ValueError as error:
        # Exit 0 without the unique trust marker is never a certificate.
        return {"status": "blocked", "reason": "marker_absent", "detail": str(error)}
    certified, offending = classify_axioms(report["axioms"], report["sorry_seen"], policy)
    extra = {"axioms": sorted(report["axioms"]), "sorry": report["sorry_seen"],
             "offending_axioms": offending}
    if certified:
        return {"status": "certified", "reason": "isolated_replay_axioms_ok", **extra}
    reason = "sorry_axiom" if report["sorry_seen"] else "unapproved_axioms"
    return {"status": "rejected", "reason": reason, **extra}


def detect_runtime() -> str | None:
    """Return a usable container runtime binary name, or ``None``."""
    for candidate in ("docker", "podman"):
        if shutil.which(candidate):
            return candidate
    return None


def image_present(runtime: str, image: str) -> bool:
    """True iff the pinned image already exists locally. Never pulls."""
    try:
        result = subprocess.run(
            [runtime, "image", "inspect", image],
            capture_output=True, text=True, timeout=30, check=False,
        )
    except (OSError, subprocess.SubprocessError):
        return False
    return result.returncode == 0


def certification_enabled(root: Path) -> bool:
    """Whether an operator has provisioned and enabled a vetted verifier image.

    Default is DISABLED: the trusted HARNESS_INTEGRATION_TESTED gate is false.
    Neither item data nor environment variables may bypass it. After real
    integration tests, enabling also requires an explicitly configured image.
    """
    if not HARNESS_INTEGRATION_TESTED:
        return False
    config = Path(root) / "benchmarks" / "quantumcomputingbench" / "configs" / "offline.json"
    try:
        lean = json.loads(config.read_text(encoding="utf-8")).get("lean", {})
    except (OSError, ValueError):
        return False
    return lean.get("status") == "ENABLED" and bool(lean.get("container_image"))


def library_mounts(root: Path) -> list:
    """Allowlisted, sanitized read-only mounts. Excludes .git/benchmark/private.

    Returns ``(host_source, container_target)`` pairs for the subset of
    :data:`LIBRARY_ALLOWLIST` that exists.  Any entry resolving to a denied path
    (``.git``, the benchmark tree, ``private``/``gold``/credentials, or outside
    ``root``) is refused.
    """
    root = Path(root).resolve()
    mounts = []
    for name in LIBRARY_ALLOWLIST:
        if any(token in Path(name).parts or token == name for token in _MOUNT_DENY):
            raise ValueError(f"denied mount entry {name!r}")
        source = (root / name).resolve()
        if not source.is_relative_to(root):
            raise ValueError(f"mount escapes repository: {name!r}")
        rel = source.relative_to(root)
        if any(part in _MOUNT_DENY for part in rel.parts):
            raise ValueError(f"denied mount path {name!r}")
        if source.exists():
            mounts.append((source, f"/library/{name}"))
    if not mounts:
        raise ValueError("no library inputs available to mount")
    return mounts


def container_command(runtime: str, image: str, root: Path, harness_dir: Path,
                      name: str) -> list:
    """Build the locked-down replay invocation (no network, non-root, caps)."""
    wall = int(LIMITS["wall_seconds"])
    inner = (
        "set -eu; cp /harness/Harness.lean /work/Harness.lean; cd /library; "
        f"exec timeout --signal=KILL {wall} lake env lean /work/Harness.lean"
    )
    command = [
        runtime, "run", "--rm", "--name", name,
        "--network", "none",
        "--read-only",
        "--user", str(LIMITS["user"]),
        "--cap-drop", "ALL",
        "--security-opt", "no-new-privileges",
        "--memory", str(LIMITS["memory"]),
        "--memory-swap", str(LIMITS["memory"]),
        "--cpus", str(LIMITS["cpus"]),
        "--pids-limit", str(LIMITS["pids"]),
        "--pull", "never",
        "--env", "HOME=/work",
        "--workdir", "/work",
        "--tmpfs", f"/work:rw,nodev,nosuid,size={LIMITS['work_size']}",
        "--mount", f"type=bind,source={harness_dir},target=/harness,readonly",
    ]
    for source, target in library_mounts(root):
        command += ["--mount", f"type=bind,source={source},target={target},readonly"]
    command += [image, "/bin/sh", "-c", inner]
    return command


def _force_remove(runtime: str, name: str) -> None:
    """Best-effort removal of a stray container after a wall-clock timeout."""
    try:
        subprocess.run([runtime, "rm", "-f", name],
                       capture_output=True, text=True, timeout=30, check=False)
    except (OSError, subprocess.SubprocessError):
        pass


def _receipt(status: str, reason: str, item: dict, image: str | None, **extra) -> dict:
    assert status in {"certified", "rejected", "blocked"}
    isolated = extra.pop("isolated", False)
    receipt = {
        "schema_version": RECEIPT_VERSION,
        "status": status,
        "reason": reason,
        "item_id": item.get("id"),
        "task_hash": item.get("task_hash"),
        "image": image,
        "isolated": isolated,
        "approved_axioms": sorted(APPROVED_AXIOMS),
    }
    receipt.update(extra)
    return receipt


def verify(root: Path, item: dict, proof: str, image: str | None = None) -> dict:
    """Independently replay a candidate Lean proof under isolation.

    Returns a receipt dict with ``status`` in ``{"certified", "rejected",
    "blocked"}``.  ``certified`` is emitted ONLY when an operator-enabled,
    isolated harness actually elaborated the frozen theorem from the candidate
    proof and its transitive ``collectAxioms`` closure was a subset of the fixed
    policy.  With the shipped ``ENV_BLOCKED`` configuration the harness is built
    but not executed and the result is ``blocked`` (reason ``env_blocked``): a
    certificate is never fabricated.
    """
    root = Path(root)

    # 1. Candidate proof grammar -- cheap, pre-sandbox gate.
    try:
        validate_proof_grammar(proof)
    except ProofGrammarError as error:
        return _receipt("rejected", "proof_grammar", item, image, detail=str(error))

    # 2. Item must carry a frozen formal statement to replay.
    try:
        _frozen_formal(item)
    except ValueError as error:
        return _receipt("blocked", "not_formal", item, image, detail=str(error))
    policy = axiom_policy(item)

    # 3. A digest-pinned image is mandatory; unpinned/none is refused, not run.
    if not image:
        return _receipt("blocked", "no_image", item, image,
                        detail="no pinned Lean image supplied")
    if not _PINNED_IMAGE.match(image):
        return _receipt("blocked", "unpinned_image", item, image,
                        detail="image must be pinned as name@sha256:<digest>")

    # 4. Certification must be explicitly enabled by a vetted operator.  Shipped
    #    config is ENV_BLOCKED -> the harness is NOT executed and nothing is
    #    certified.  We build the harness only after confirming we may run it.
    if not certification_enabled(root):
        return _receipt("blocked", "env_blocked", item, image,
                        detail="Lean certification disabled (configs/offline.json "
                               "lean.status=ENV_BLOCKED); harness generated but not executed")

    # 5. A container runtime must exist, with the image already present locally.
    runtime = detect_runtime()
    if not runtime:
        return _receipt("blocked", "no_runtime", item, image,
                        detail="no container runtime (docker/podman) available")
    if not image_present(runtime, image):
        return _receipt("blocked", "image_absent", item, image,
                        detail="pinned image not present locally; refusing to pull")

    # 6. Build the trusted harness around the grammar-checked proof.
    nonce = secrets.token_hex(16)
    try:
        source, theorem = build_harness(item, proof, nonce)
    except (ValueError, ProofGrammarError) as error:
        return _receipt("blocked", "harness_build", item, image, detail=str(error))
    harness_sha = hashlib.sha256(source.encode()).hexdigest()
    container_name = "qcb-lean-" + nonce[:16]

    # 7. Replay inside the sandbox.
    tmp = Path(tempfile.mkdtemp(prefix="qcb-lean-"))
    try:
        (tmp / "Harness.lean").write_text(source, encoding="utf-8")
        try:
            command = container_command(runtime, image, root, tmp, container_name)
        except ValueError as error:
            return _receipt("blocked", "mount_error", item, image, detail=str(error))
        try:
            result = subprocess.run(
                command, capture_output=True, text=True,
                timeout=LIMITS["wall_seconds"] + 60, check=False,
            )
        except subprocess.TimeoutExpired:
            _force_remove(runtime, container_name)
            return _receipt("blocked", "wall_timeout", item, image, isolated=True,
                            theorem=theorem, harness_sha256=harness_sha,
                            detail="replay exceeded the wall-clock cap")
        except OSError as error:
            _force_remove(runtime, container_name)
            return _receipt("blocked", "runtime_error", item, image,
                            detail=f"runtime invocation failed: {error}")

        stdout = (result.stdout or "")[: LIMITS["stdout_cap"]]
        stderr = (result.stderr or "")[-LIMITS["stderr_cap"]:]
        outcome = evaluate_report(result.returncode, stdout, stderr, nonce, policy)
        base = {"isolated": True, "theorem": theorem, "harness_sha256": harness_sha,
                "exit_code": result.returncode, "runtime": runtime}
        if outcome["status"] == "rejected" and outcome["reason"] == "unproven":
            base["stderr"] = stderr.strip()
        status = outcome.pop("status")
        reason = outcome.pop("reason")
        return _receipt(status, reason, item, image, **base, **outcome)
    finally:
        _force_remove(runtime, container_name)
        shutil.rmtree(tmp, ignore_errors=True)
