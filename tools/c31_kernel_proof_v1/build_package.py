"""Build reproducible source-proof bindings and complete own CI4 observed baseline."""
import hashlib
import json
from pathlib import Path
import shutil
import sys

import compare
import proof_patch
import runtime


def build(project,package,public,lean_api):
    packages={}
    for version,manifest,seal in [('v1','proposal-bindings.json','proposal-seal.json'),
        ('ci2','ci2-bindings.json','ci2-seal.json'),('ci3','ci3-bindings.json','ci3-seal.json'),
        ('ci4','ci4-bindings.json','ci4-seal.json')]:
        relative='tools/primitive_compiler_native_profile_'+version; root=project/relative
        files=runtime.read(root/manifest)['files']
        runtime.verify(root,files)
        packages[relative]=dict(files,**{manifest:runtime.sha(root/manifest),seal:runtime.sha(root/seal)})
    receipts=runtime.read(public/'raw-derivation-receipts.json')['files']
    names={p.name for p in public.iterdir() if p.is_file()}
    if len(receipts)!=len(names)-1 or {r['publicRelativePath'] for r in receipts}!=names-{'raw-derivation-receipts.json'}:
        raise ValueError('actual CI4 public receipt partition drift')
    for receipt in receipts:
        path=receipt['publicRelativePath']
        if Path(path).name!=path or runtime.sha(public/path)!=receipt['publicSHA256']:
            raise ValueError('actual public derivative hash mismatch')
    raw=(project/'tools/primitive_compiler_native_profile_v1/profile.json').read_bytes()
    if proof_patch.sha(raw)!='72c0931c4c62906835d831742a3b797b381e947fbb8e3ecb58c4ad62aaa64473':
        raise ValueError('old raw87 profile drift')
    original=json.loads(raw); original_inputs=runtime.read(public/'input-bindings.json')
    if {r['relativePath']:r['sha256'] for r in original_inputs['projectInputs']}!=original['projectInputs']:
        raise ValueError('actual old 31 input pins differ')
    candidate,sites=proof_patch.candidate((project/proof_patch.RELATIVE).read_bytes())
    if candidate!=(package/'candidate'/proof_patch.RELATIVE).read_bytes(): raise ValueError('candidate raw bytes differ')
    sha_new=proof_patch.sha(candidate)
    if raw.count(proof_patch.ORIGINAL_SHA.encode())!=2: raise ValueError('profile raw replacement boundary')
    derivedraw=raw.replace(proof_patch.ORIGINAL_SHA.encode(),sha_new.encode())
    proof_patch.validate_derivation(original,json.loads(derivedraw),sha_new)
    # These are generated byte-preserving input views, not edits of original packages.
    with (package/'original-profile.json').open('xb') as out: out.write(raw)
    with (package/'profile.json').open('xb') as out: out.write(derivedraw)
    config=dict(schema='C31_EXACT_PROOF_KERNEL_SUCCESSOR_V1',wholeSeconds=2100,budgetMiB=5120,reserveMiB=2048,threads=1,
        runtimePackages=packages,originalProfileSHA256=proof_patch.sha(raw),candidateProfileSHA256=proof_patch.sha(derivedraw),
        originalTargetSHA256=proof_patch.ORIGINAL_SHA,candidateTargetSHA256=sha_new,
        nativeKernelAPISourceSHA256=runtime.sha(lean_api),
        direction='formal-only exact proof-token kernel successor; actual-owned whole-module comparison',
        baselineCandidateGeneratedCount=None,**runtime.NO_ACCEPT)
    ci4,ci2,base,p1,observed_profile,api=runtime.load_runtime(project,config)
    text=(public/'30-observe.stdout.raw.sanitized.txt').read_text(encoding='utf-8')
    records=base.validator.parse(text); bindings=records['C31_BINDING_JSON']; summary=records['C31_SUMMARY_JSON'][0]
    checked=base.validator.validate(original,text,0,timed_out=False,profile_sha=runtime.sha(package/'original-profile.json'),
        cohort_id=summary['cohortID'],expected_oleans={b['module']:b['resolvedOleanPath'] for b in bindings})
    if checked!=runtime.read(public/'completeness.json'): raise ValueError('actual complete stream result differs')
    actual=[r for tag in compare.TAGS for r in records[tag]]
    native=[r for r in actual if r['actualKind']=='axiomInfo' and r['selfOccursInAxioms']]
    expected={s['sourceName']+'._native.native_decide.ax_1_1' for s in sites}
    if len(native)!=3 or {r['actualName'] for r in native}!=expected or \
        any(r['module']!='QuantumBlockEncoding.CubicAmplitudePrimitive' for r in native):
        raise ValueError('actual three self native axiom/source ownership mismatch')
    for site in sites:
        root=next(r for r in records['C31_ROOT_JSON'] if r['sourceUserName']==site['sourceName'])
        axiom=site['sourceName']+'._native.native_decide.ax_1_1'
        if axiom not in root['axioms']: raise ValueError('source proof/root recursive axiom linkage absent')
        site.update(actualOwnerModule='QuantumBlockEncoding.CubicAmplitudePrimitive',actualNativeAxiom=axiom,
            actualOldRootSignatureSHA256=compare.digest({k:root[k] for k in compare.SIG}))
    baseline=dict(schema='C31_ACTUAL_CI4_OWNED_BASELINE_V1',rows=compare.normalized(records),
        targetNativeAxioms=sorted(expected),observedOwned=checked['owned'],observedRoots=87,
        observedGenerated=checked['generated'],rawSanitizedStreamSHA256=runtime.sha(public/'30-observe.stdout.raw.sanitized.txt'),
        derivationReceiptsSHA256=runtime.sha(public/'raw-derivation-receipts.json'),
        actualPublicMemberSHA256={name:runtime.sha(public/name) for name in sorted(names)},
        publicDerivativeReceiptCount=len(receipts),originalProfileSHA256=proof_patch.sha(raw),
        structures={b['module']:b['structures'] for b in bindings},
        boundary='Actual own sanitized CI4 stream revalidated; redacted paths are not independent raw OS-path reconstruction. Candidate generated identities/count remain unprescribed.',
        **runtime.NO_ACCEPT)
    runtime.write(package/'baseline.json',baseline); runtime.write(package/'proof-sites.json',dict(sites=sites,
        originalSourceSHA256=proof_patch.ORIGINAL_SHA,candidateSourceSHA256=sha_new,exactInverseRestoresOriginalBytes=True,
        localLeanInvocationCount=0,**runtime.NO_ACCEPT))
    config['baselineSHA256']=runtime.sha(package/'baseline.json')
    runtime.write(package/'kernel-profile.json',config)
    print(json.dumps(dict(actualOldRoots=87,actualOldOwned=checked['owned'],actualOldGenerated=checked['generated'],
        actualSelfNativeAxioms=[r['actualName'] for r in native],candidateTargetSHA256=sha_new,
        candidateRawProfileSHA256=proof_patch.sha(derivedraw),localLeanInvocationCount=0)))


if __name__=='__main__':
    project,public,lean_api=map(Path,sys.argv[1:4])
    build(project.resolve(),Path(__file__).parent.resolve(),public.resolve(),lean_api.resolve())
